import assert from 'node:assert/strict';
import fs from 'node:fs';
import clipping from 'polygon-clipping';
import {coastalTransition,coastHeight,COAST_STEPS,bakeShelf} from '../preview/sea/coastal-transition.ts';

const geo=JSON.parse(fs.readFileSync(new URL('../public/data/singapore-regions.geojson',import.meta.url)));
const coast=JSON.parse(fs.readFileSync(new URL('../public/data/singapore-coastlines.json',import.meta.url)));
const original=JSON.stringify({geo,coast});
const west=geo.features.find(f=>f.properties.REGION_N==='WEST REGION');
const bounds=[103.65,1.202,103.80,1.327], [w,s,e,n]=bounds;
const local=([x,y])=>[(x-103.73)*70,-(y-1.267)*70];
const rings=clipping.intersection(west.geometry.coordinates,[[[w,s],[e,s],[e,n],[w,n],[w,s]]]).map(p=>p[0].map(local));
const segs=coast['WEST REGION'].filter(r=>r.length===2&&r.every(p=>p[0]>=w&&p[0]<=e&&p[1]>=s&&p[1]<=n)).map(r=>r.map(local));
const result=coastalTransition(segs,rings), p=result.geometry.getAttribute('position'), normals=result.geometry.getAttribute('normal');
assert(p.count>0);
for(const v of p.array)assert(Number.isFinite(v));
for(const v of normals.array)assert(Number.isFinite(v));
const ys=Array.from({length:p.count},(_,i)=>p.getY(i));
const minY=ys.reduce((a,b)=>Math.min(a,b)),maxY=ys.reduce((a,b)=>Math.max(a,b));
assert(minY<-.40,'apron enters below the fixed -0.10 sea');
assert(Math.abs(maxY-.5205)<1e-6,'curve starts at the original land surface, not at the wall foot');
assert(COAST_STEPS>=20);
for(let i=1;i<=100;i++)assert(coastHeight(i/100)<coastHeight((i-1)/100),'continuous descent without ledges');
assert(Math.abs(coastHeight(.0001)-coastHeight(0))<1e-9,'smooth tangent at land surface');
assert(Math.abs(coastHeight(.9999)-coastHeight(1))<1e-9,'smooth tangent at submerged shelf');
const depth=bakeShelf(result.geometry,1024,[48,38]);
assert(Array.from(depth).every(Number.isFinite));
assert(depth.some(h=>h>-.15&&h<-.05),'waterline represented in geometry-derived depth');
assert(depth.some(h=>h<-.25&&h>-.5),'submerged shelf represented in depth');
assert.equal(depth[0],-1,'outer water remains deeper');
const keys=new Set(segs.map(s=>JSON.stringify(s)));
assert(result.segments.every(s=>keys.has(JSON.stringify(s))),'only original marine segments, not new crop seams');
assert.equal(JSON.stringify({geo,coast}),original,'source geometry is immutable');
const second=coastalTransition(segs,rings);
assert.deepEqual(second.geometry.getAttribute('position').array,p.array,'deterministic mesh');
const square=[[-2,-2],[2,-2],[2,2],[-2,2],[-2,-2]];
const exclusion=coastalTransition([[[0,0],[.2,0]],[[10,10],[11,10]],[square[0],square[1]]],[square]);
assert.equal(exclusion.segments.length,1,'reject land-interior and off-land segments');
console.log(JSON.stringify({status:'PASS',marineSegments:result.stats.marineSegments,apronTriangles:result.stats.triangles,yRange:[minY,maxY],checks:['finite geometry/normals','continuous profile and endpoint tangents','geometry-derived shallow depth','submerged foot','original coast only','immutable source','deterministic mesh','interior/off-land rejection']}));
result.geometry.dispose();second.geometry.dispose();exclusion.geometry.dispose();
